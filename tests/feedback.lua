local t = dofile("tests/helpers.lua")
local ui = require("ui_tools")
local buf = t.buffer({ "中文 sample", "", "last" })
local ns = vim.api.nvim_create_namespace("UiToolsFeedback")
local first = ui.flash({ line = 1, timeout = 0 })
local second = ui.flash({ range = { 0, 0, 0, 6 }, timeout = 20 })
t.eq(2, #vim.api.nvim_buf_get_extmarks(buf, ns, 0, -1, {}))
assert(vim.wait(300, function()
  return not second:is_active()
end))
assert(first:is_active())
first:cancel()
first:cancel()
t.eq(0, #vim.api.nvim_buf_get_extmarks(buf, ns, 0, -1, {}))
assert(not pcall(ui.flash, { range = { 2, 4, 1, 0 } }))
local handle = ui.flash({ line = 2, timeout = 0 })
vim.api.nvim_buf_delete(buf, { force = true })
assert(not handle:is_active())
ui.setup({ guide = { columns = { 81, 121 } }, feedback = { yank = true } })
ui.setup({ guide = true, feedback = { yank = true } })
local callbacks = vim.api.nvim_get_autocmds({ group = "UiToolsFeedback", event = "TextYankPost" })
t.eq(1, #callbacks)
ui.disable()
assert(not pcall(ui.setup, { guide = { columns = { 0 } } }))
print("feedback: independent ranges, expiry, cancellation, buffer deletion and repeated setup passed")
