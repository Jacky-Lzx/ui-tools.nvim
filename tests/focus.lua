local t = dofile("tests/helpers.lua")
local ui = require("ui_tools")
local buf = t.buffer({ "one", "two", "three" })
vim.cmd("vsplit")
local source = vim.api.nvim_get_current_win()
local layout = vim.fn.winlayout()
local widths = {}
for _, win in ipairs(vim.api.nvim_list_wins()) do
  widths[win] = vim.api.nvim_win_get_width(win)
end
vim.wo.number = true
ui.setup({ focus = { width = 50 } })
local focused = ui.zen()
assert(focused ~= source)
t.eq(buf, vim.api.nvim_win_get_buf(focused))
vim.api.nvim_buf_set_lines(buf, 1, 2, false, { "edited" })
vim.api.nvim_win_set_cursor(focused, { 3, 0 })
ui.zen()
t.eq(nil, require("ui_tools.focus").state())
t.eq(layout, vim.fn.winlayout())
t.eq(source, vim.api.nvim_get_current_win())
t.eq({ 3, 0 }, vim.api.nvim_win_get_cursor(source))
t.eq(true, vim.wo.number)
for win, width in pairs(widths) do
  t.eq(width, vim.api.nvim_win_get_width(win))
end
t.eq("edited", vim.api.nvim_buf_get_lines(buf, 1, 2, false)[1])
ui.zoom()
t.eq("zoom", require("ui_tools.focus").state().mode)
ui.zen()
t.eq("zen", require("ui_tools.focus").state().mode)
ui.disable()
t.eq(layout, vim.fn.winlayout())
ui.zen()
local win = require("ui_tools.focus").state().win
vim.api.nvim_win_set_cursor(win, { 2, 0 })
vim.api.nvim_win_close(win, true)
assert(vim.wait(300, function()
  return require("ui_tools.focus").state() == nil
end))
t.eq(2, #vim.api.nvim_list_wins())
t.eq({ 2, 0 }, vim.api.nvim_win_get_cursor(source))
ui.zen()
local other = vim.api.nvim_create_buf(true, false)
vim.api.nvim_buf_set_lines(other, 0, -1, false, { "keep this unsaved buffer" })
vim.bo[other].bufhidden = "wipe"
vim.api.nvim_win_set_buf(0, other)
ui.zen()
t.eq(other, vim.api.nvim_get_current_buf())
assert(vim.api.nvim_buf_is_valid(other))
t.eq(true, vim.bo[other].modified)
ui.zoom()
vim.cmd("tabnew")
t.eq(nil, require("ui_tools.focus").state())
ui.disable()
print("focus: layout/options/view preservation, editing, mode switch, manual close and tab leave passed")
