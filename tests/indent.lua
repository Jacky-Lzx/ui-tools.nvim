local t = dofile("tests/helpers.lua")
local ui = require("ui_tools")
t.eq(nil, next(require("ui_tools.render").sources))
local buf = t.buffer({ "function main()", "  if ready then", "    run()", "", "    done()", "  end", "end" })
local scope = require("ui_tools.scope")
t.eq(8, scope.width("\t\tx", 4))
local block = scope.find(buf, 3, 400)
t.eq({ first = 2, last = 5, column = 2, body = 4 }, block)
t.eq(block, scope.find(buf, 2, 400))
ui.setup({ indent = { only_scope = true } })
assert(require("ui_tools.render").sources.indent)
ui.toggle("indent")
t.eq(nil, require("ui_tools.render").sources.indent)
ui.toggle("indent")
ui.setup({})
t.eq(nil, next(require("ui_tools.render").sources))
assert(not pcall(ui.setup, { indent = { char = "ab" } }))
ui.disable()
print("indent: scope, tabs, blank lines, explicit opt-in and lifecycle passed")
