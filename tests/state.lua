vim.opt.rtp:prepend(vim.fn.getcwd())
local plugin = require("ui_tools")
local commands, handlers = vim.api.nvim_get_commands({}), vim.api.nvim_get_autocmds({})
assert(plugin.get_state("indent") == nil and plugin.get_state("focus") == nil)
assert(not package.loaded["ui_tools.indent"] and not package.loaded["ui_tools.focus"])
assert(vim.deep_equal(commands, vim.api.nvim_get_commands({})))
assert(vim.deep_equal(handlers, vim.api.nvim_get_autocmds({})))
plugin.setup({ indent = true, focus = true })
local state = plugin.get_state("indent")
assert(state.enabled)
state.enabled = false
assert(plugin.get_state("indent").enabled)
plugin.zen()
assert(plugin.get_state("focus").mode == "zen")
plugin.zen()
assert(plugin.get_state("focus").mode == nil)
plugin.dispose()
assert(plugin.get_state("indent").enabled == false)
print("UI public state: cold reads, focus transitions and snapshot ownership passed")
